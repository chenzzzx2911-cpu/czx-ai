import json, os

_BAZI_VERNACULAR = None

def _load_vernacular():
    global _BAZI_VERNACULAR
    if _BAZI_VERNACULAR is None:
        path = os.path.join(os.path.dirname(__file__), 'vernacular_data.json')
        with open(path, encoding='utf-8') as f:
            _BAZI_VERNACULAR = json.load(f)
    return _BAZI_VERNACULAR

def get_day_master_vernacular(day_gan: str) -> dict:
    """获取日主白话解读"""
    data = _load_vernacular()
    return data.get("day_masters", {}).get(day_gan, {})

def get_pattern_vernacular(pattern_name: str) -> str:
    """获取格局白话解读"""
    data = _load_vernacular()
    return data.get("patterns", {}).get(pattern_name, "")

